"""Uploads built models to Roblox and writes the game's mesh catalog.

Needs two environment variables (set in the cloud environment's settings, never in code):
    ROBLOX_API_KEY   Open Cloud API key with Assets read + write
    ROBLOX_USER_ID   the Roblox user ID that owns the game

Usage (from the repo root):
    python tools/meshes/upload.py AcousticGuitar GoldTrophy ...
    python tools/meshes/upload.py --all
    python tools/meshes/upload.py --catalog-only    (just rewrite the Luau catalog)

New models are created; changed models get a new version of the same asset.
Asset IDs are saved in assets/meshes/uploaded.json, and the Luau catalog the game
reads is written to src/server/MeshCatalog.luau.
"""

import hashlib
import json
import os
import sys
import time
import urllib.error
import urllib.request
import uuid

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
MESHES = os.path.join(ROOT, "assets", "meshes")
UPLOADED = os.path.join(MESHES, "uploaded.json")
CATALOG = os.path.join(ROOT, "src", "server", "MeshCatalog.luau")
API = "https://apis.roblox.com/assets/v1"


def _request(method, url, body=None, headers=None):
    req = urllib.request.Request(url, data=body, method=method, headers=headers or {})
    req.add_header("x-api-key", os.environ["ROBLOX_API_KEY"])
    try:
        with urllib.request.urlopen(req, timeout=120) as resp:
            return json.loads(resp.read() or b"{}")
    except urllib.error.HTTPError as e:
        raise RuntimeError(f"{method} {url} failed: {e.code} {e.read().decode(errors='replace')}") from None


def _multipart(request_json, file_path):
    boundary = uuid.uuid4().hex
    with open(file_path, "rb") as f:
        data = f.read()
    parts = [
        f"--{boundary}\r\nContent-Disposition: form-data; name=\"request\"\r\n"
        f"Content-Type: application/json\r\n\r\n{json.dumps(request_json)}\r\n".encode(),
        f"--{boundary}\r\nContent-Disposition: form-data; name=\"fileContent\"; "
        f"filename=\"{os.path.basename(file_path)}\"\r\nContent-Type: model/fbx\r\n\r\n".encode(),
        data,
        f"\r\n--{boundary}--\r\n".encode(),
    ]
    return b"".join(parts), {"Content-Type": f"multipart/form-data; boundary={boundary}"}


def _wait_for(operation):
    op_id = operation["path"].split("/")[-1]
    for _ in range(60):
        result = _request("GET", f"{API}/operations/{op_id}")
        if result.get("done"):
            if "error" in result:
                raise RuntimeError(f"Upload failed: {result['error']}")
            return result["response"]
        time.sleep(2)
    raise RuntimeError("Upload is taking too long; try again later.")


def upload(model_id, uploaded):
    fbx = os.path.join(MESHES, model_id + ".fbx")
    with open(fbx, "rb") as f:
        digest = hashlib.sha256(f.read()).hexdigest()
    existing = uploaded.get(model_id)
    if existing and existing.get("sha256") == digest:
        print(f"{model_id}: unchanged (asset {existing['assetId']})")
        return
    if existing:
        body, headers = _multipart({"assetId": existing["assetId"]}, fbx)
        op = _request("PATCH", f"{API}/assets/{existing['assetId']}", body, headers)
        response = _wait_for(op)
        asset_id = existing["assetId"]
        print(f"{model_id}: updated asset {asset_id} (new version)")
    else:
        body, headers = _multipart({
            "assetType": "Model",
            "displayName": f"PawnShop_{model_id}",
            "description": "Pawn Shop Simulator item model",
            "creationContext": {"creator": {"userId": str(os.environ["ROBLOX_USER_ID"])}},
        }, fbx)
        op = _request("POST", f"{API}/assets", body, headers)
        response = _wait_for(op)
        asset_id = int(response["assetId"])
        print(f"{model_id}: uploaded as asset {asset_id}")
    uploaded[model_id] = {"assetId": int(asset_id), "sha256": digest}


def _lua_color(c):
    return f"Color3.fromRGB({c[0]}, {c[1]}, {c[2]})"


def write_catalog(uploaded):
    lines = [
        "-- AUTO-GENERATED by tools/meshes/upload.py. Don't edit by hand.",
        "-- Detailed mesh models uploaded to Roblox: asset ID, intended size (studs),",
        "-- and the color/material for each part of the model.",
        "",
        "return {",
    ]
    for model_id in sorted(uploaded):
        info_path = os.path.join(MESHES, model_id + ".json")
        if not os.path.exists(info_path):
            continue
        with open(info_path) as f:
            info = json.load(f)
        size = info["Size"]
        lines.append(f"\t{model_id} = {{")
        lines.append(f"\t\tAssetId = {uploaded[model_id]['assetId']},")
        lines.append(f"\t\tSize = Vector3.new({size[0]}, {size[1]}, {size[2]}),")
        if "Origin" in info:
            o = info["Origin"]
            lines.append(f"\t\tOrigin = Vector3.new({o[0]}, {o[1]}, {o[2]}),")
        lines.append("\t\tParts = {")
        for name, look in sorted(info["Parts"].items()):
            lines.append(
                f"\t\t\t{name} = {{ Color = {_lua_color(look['Color'])}, Material = Enum.Material.{look['Material']}, "
                f"Transparency = {look['Transparency']}, Reflectance = {look['Reflectance']} }},"
            )
        lines.append("\t\t},")
        lines.append("\t},")
    lines.append("}")
    with open(CATALOG, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"Wrote {os.path.relpath(CATALOG, ROOT)} ({len(uploaded)} models)")


def main():
    uploaded = {}
    if os.path.exists(UPLOADED):
        with open(UPLOADED) as f:
            uploaded = json.load(f)
    if "--catalog-only" not in sys.argv:
        for var in ("ROBLOX_API_KEY", "ROBLOX_USER_ID"):
            if not os.environ.get(var):
                sys.exit(f"Missing environment variable {var}. Add it in the cloud environment settings.")
        ids = [a for a in sys.argv[1:] if not a.startswith("--")]
        if "--all" in sys.argv:
            ids = sorted(f[:-4] for f in os.listdir(MESHES) if f.endswith(".fbx"))
        for model_id in ids:
            upload(model_id, uploaded)
            with open(UPLOADED, "w") as f:
                json.dump(uploaded, f, indent=2, sort_keys=True)
    write_catalog(uploaded)


if __name__ == "__main__":
    main()
